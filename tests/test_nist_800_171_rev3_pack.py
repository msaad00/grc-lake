def _controls() -> dict[str, dict]:
    return {cid: row for cid, row in load_control_catalog().items() if row["framework_id"] == FRAMEWORK_ID}


def _members() -> list[tuple[str, dict]]:
    return [
        (entry["safeguard_id"], member)
        for entry in load_safeguards()["safeguards"]
        for member in entry["satisfies"]
        if member["framework_id"] == FRAMEWORK_ID
    ]


def test_manifest_is_every_active_rev3_requirement() -> None:
    ids = [row["id"] for row in MANIFEST["rows"]]
    assert len(ids) == len(set(ids)) == 97
    assert all(re.fullmatch(r"03\.\d{2}\.\d{2}", i) for i in ids)
    assert Counter(row["family"] for row in MANIFEST["rows"]) == FAMILY_COUNTS
    assert set(MANIFEST["families"]) == set(FAMILY_COUNTS)
    for row in MANIFEST["rows"]:
        assert 0 < len(row["title"]) <= 80, row["id"]
        assert row["id"].startswith(row["family"] + ".")


def test_sources_are_pinned() -> None:
    source = MANIFEST["source"]
    assert source["oscal_commit"] == OSCAL_COMMIT
    for key in ("catalog_sha256", "pdf_sha256"):
        assert re.fullmatch(r"[0-9a-f]{64}", source[key]), key
    assert source["pdf"] == "https://nvlpubs.nist.gov/nistpubs/SpecialPublications/NIST.SP.800-171r3.pdf"
    analysis = source["r2_r3_analysis"]
    assert analysis["url"].startswith("https://csrc.nist.gov/files/pubs/sp/800/171/r3/final/docs/")
    assert re.fullmatch(r"[0-9a-f]{64}", analysis["sha256"])
    registry = load_framework_registry()[FRAMEWORK_ID]
    assert registry["source_sha256"] == source["catalog_sha256"]
    assert registry["pulled_at"] == source["pulled_at"]
    assert registry["implementation_status"] == "implemented_limited_mapping"
    assert registry["official_source_url"] == "https://csrc.nist.gov/pubs/sp/800/171/r3/final"


def test_r2_relationships_only_cite_real_rev2_requirements() -> None:
    """Every Rev 2 -> Rev 3 link comes from NIST's analysis and names a real Rev 2 id."""
    r2_ids = {row["id"] for row in CMMC["requirements"]}
    accounted: set[str] = set()
    for row in MANIFEST["rows"]:
        for link in row["r2_predecessors"]:
            assert link["id"] in r2_ids, (row["id"], link)
            assert link["relationship"] in {"carried_forward", "incorporated_into"}
            accounted.add(link["id"])
    for entry in MANIFEST["r2_not_carried"]:
        assert entry["id"] in r2_ids
        assert entry["reason"]
        accounted.add(entry["id"])
    # All 110 Rev 2 requirements are accounted for, once as a predecessor or a withdrawal.
    assert accounted == r2_ids
    anomalies = MANIFEST["source_anomalies"]
    assert [a["analysis_r2_id"] for a in anomalies] == ["3.11.4"]


