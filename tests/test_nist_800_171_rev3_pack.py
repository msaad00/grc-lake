def test_every_control_has_evidence_types_and_hints() -> None:
    for control_id, control in _controls().items():
        assert control["required_evidence_types"], control_id
        article_id = control_id.removeprefix(PREFIX)
        hints = resolve_connector_hints(framework_id=FRAMEWORK_ID, control=control, article_ids=[article_id])
        assert hints and hints[0]["priority"] == "primary", control_id
        assert _framework_from_control(control_id) == FRAMEWORK_ID


def test_safeguard_mappings_are_proposed_cited_and_leave_lanes_alone() -> None:
    payload = load_safeguards()
    assert validate_safeguards(payload) == []
    pdf = MANIFEST["source"]["pdf"]
    analysis = MANIFEST["source"]["r2_r3_analysis"]
    rows = {row["id"]: row for row in MANIFEST["rows"]}
    lanes = {entry["safeguard_id"] for entry in payload["safeguards"] if "mapping_source" in entry}
    for sid, member in _members():
        assert sid not in lanes, (sid, member["control_id"])
        assert member["review_status"] == "proposed"
        expected_role = (
            "primary" if sid in {"SG-INFORMATIONEXCHANGE-001", "SG-PERSONNELSCREENING-001"} else "equivalent"
        )
        assert member["role"] == expected_role
        assert "review_basis" not in member
        source = member["mapping_source"]
        requirement = member["control_id"].removeprefix(PREFIX)
        if source["url"] == analysis["url"]:
            assert source["sha256"] == analysis["sha256"]
            predecessor = re.search(r"Rev 2 (3\.\d+\.\d+) ", source["locator"]).group(1)
            assert predecessor in {p["id"] for p in rows[requirement]["r2_predecessors"]}
            assert f"Rev 3 {requirement}" in source["locator"]
        else:
            assert source["url"] == pdf
            assert source["sha256"] == MANIFEST["source"]["pdf_sha256"]
            assert source["locator"].endswith(f"requirement {requirement}")


def test_unmapped_requirements_are_exactly_the_documented_gaps() -> None:
    mapped = {member["control_id"].removeprefix(PREFIX) for _, member in _members()}
    assert set(rows := {row["id"] for row in MANIFEST["rows"]}) - mapped == set(UNMAPPED)
    assert mapped <= rows
    gaps = {gap["id"]: gap for gap in MANIFEST["unmapped"]}
    assert set(gaps) == set(UNMAPPED)
    for requirement, reason in UNMAPPED.items():
        assert gaps[requirement]["reason"], requirement
        if reason == "lane":
            assert "lane" in gaps[requirement]["reason"]
    coverage = coverage_by_framework()["frameworks"][FRAMEWORK_ID]
    assert coverage["controls"] == 97
    assert coverage["covered"] == 97 - len(UNMAPPED)
    assert coverage["maintainer_reviewed"] == coverage["org_reviewed"] == 0


def test_sync_tool_reproduces_the_manifest_offline(tmp_path: Path) -> None:
    sys.path.insert(0, str(ROOT / "tools"))
    import sync_nist_800_171r3 as tool

    assert tool.OSCAL_COMMIT == OSCAL_COMMIT
    rows = tool.parse_analysis_rows(tool.read_xlsx_rows(_tiny_workbook(tmp_path)))
    assert rows[0]["r2"] == "3.1.1" and rows[0]["r3"] == "03.01.01"
    assert rows[1]["withdrawn_text"] == "Incorporated into 03.01.12."


def _tiny_workbook(tmp_path: Path) -> Path:
    """A two-row xlsx in the analysis layout, built with the stdlib only."""
    import zipfile

    header = [
        "Family",
        "R2 SORT-ID",
        "R2 Identifier",
        "R2 Requirement",
        "Basic or Derived",
        "R3 SORT-ID",
        "R3 Identifier",
        "Requirement Name",
        "R3 Requirement",
        "No Significant Change",
        "Significant Change",
        "Minor Change",
        "New ODP",
        "New Requirement",
        "Withdrawn Requirement",
        "Summary",
    ]
    data = [
        header,
        ["Access Control", "R2-03-01-01", "3.1.1", "x", "Basic", "R3-03-01-01", "03.01.01", "Account Management"]
        + ["y", "", "X", "", "X", "", "", "s"],
        ["Access Control", "R2-03-01-13", "3.1.13", "x", "Derived", "R3-03-01-13", "03.01.13", "Withdrawn"]
        + ["Incorporated into 03.01.12.", "", "", "", "", "", "X", ""],
    ]

    def cell(ref: str, value: str) -> str:
        return f'<c r="{ref}" t="inlineStr"><is><t>{value}</t></is></c>' if value else ""

    letters = "ABCDEFGHIJKLMNOP"
    sheet_rows = "".join(
        f'<row r="{r + 1}">' + "".join(cell(f"{letters[c]}{r + 1}", v) for c, v in enumerate(row)) + "</row>"
        for r, row in enumerate(data)
    )
    path = tmp_path / "analysis.xlsx"
    ns = 'xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"'
    rel_ns = 'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"'
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr(
            "xl/workbook.xml",
            f'<workbook {ns} {rel_ns}><sheets><sheet name="{tool_sheet()}" sheetId="1" r:id="rId1"/></sheets></workbook>',
        )
        archive.writestr(
            "xl/_rels/workbook.xml.rels",
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Target="worksheets/sheet1.xml" '
            'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet"/></Relationships>',
        )
        archive.writestr("xl/worksheets/sheet1.xml", f"<worksheet {ns}><sheetData>{sheet_rows}</sheetData></worksheet>")
    return path


def tool_sheet() -> str:
    import sync_nist_800_171r3 as tool

