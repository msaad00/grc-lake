def test_catalog_rows_are_generated_from_the_builder() -> None:
    controls = _controls()
    specs = nist_800_171_rev3_specs()
    assert [s.article_id for s in specs] == [row["id"] for row in MANIFEST["rows"]]
    assert set(controls) == {PREFIX + row["id"] for row in MANIFEST["rows"]}
    mappings = load_control_article_mappings()
    for spec in specs:
        assert controls[spec.control_id] == pack_control_row(spec)
        assert mappings[spec.control_id] == pack_mapping_row(spec)
    assert "nist-800-171-rev3" in PACK_BUILDERS
    assert validate_catalog() == []


def test_review_state_is_honest() -> None:
    assert SOURCE_RECONCILED_PACKS[FRAMEWORK_ID] == MANIFEST["source"]["pulled_at"]
    for control in _controls().values():
        assert control["review_status"] == "proposed"
